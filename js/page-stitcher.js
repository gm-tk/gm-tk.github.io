'use strict';

/**
 * PageStitcher — recombines a SPLIT module (a base homepage + per-section files)
 * back into ONE single-page module HTML, identical to how single-page modules
 * are normally built (e.g. BLL210: all lessons in one #body, delimited by their
 * own <!-- N --> comments).
 *
 * It is used when the downstream HTML Convertor ran in SPLIT MODE — emitting a
 * long single-page module in pieces so each generation stayed within length
 * limits. See SPLIT_MODE_AND_STITCH_CONTRACT.md for the authoritative contract.
 *
 * The INSERTION CONTRACT is explicit (never positional guesswork, spec §8.1):
 *   - The base homepage's #body contains ordered splice markers, one per slot:
 *         <!-- PAGEFORGE-SPLICE id="01" -->
 *   - Each section file carries its id + content between section markers:
 *         <!-- PAGEFORGE-SECTION id="01" -->  …raw #body chunk…  <!-- /PAGEFORGE-SECTION -->
 *   - The stitcher replaces each splice marker with its matching section's
 *     content, preserving document order and the surrounding scaffold untouched.
 *   - Manual-stitch GUIDE blocks the Convertor adds for hand-assembly
 *     (<!-- PAGEFORGE-GUIDE-START --> … <!-- PAGEFORGE-GUIDE-END -->) are stripped,
 *     so the unified output carries none of those developer instructions.
 *
 * SECOND JOB (2026-07-28) — INTERACTIVE INSERTION. The same Stitch button also
 * accepts the OTHER recombination: module pages generated by the HTML Generator
 * (V2) in EXTRACT mode, where every un-built interactive is a single reference
 * marker <div class="cv2-int-ref" data-cv2-ref="CODE-NN-SS">CODE-INT-NN-SS-type</div>,
 * plus the built-interactives file(s) from the Interactives Claude project,
 * where every finished build is wrapped
 * <section class="cv2-built" data-cv2-ref="CODE-INT-NN-SS-type"> … </section>.
 * Each build replaces its marker in place; both anchors are removed in the
 * output. Which job runs is auto-detected from the uploaded files — see
 * SPLIT_MODE_AND_STITCH_CONTRACT.md §10.
 *
 * Pure, string/regex based (no DOM) → headless-testable; the upload/file-read
 * adapter lives in the Page Stitcher mode controller.
 */
class PageStitcher {
    /** @param {Object} [options] @param {Object} [options.config] marker tags. */
    constructor(options) {
        options = options || {};
        this.config = options.config || PageStitcher.DEFAULTS;
    }

    // ------------------------------------------------------------------
    // Public: stitch over uploaded section files (array of {name, html})
    // ------------------------------------------------------------------

    /**
     * @param {string} baseHtml - the base homepage (with splice markers).
     * @param {Array<{name:string, html:string}>} sections - the section files.
     * @returns {{ok:boolean, html:?string, errors:string[], placements:Array}}
     */
    stitch(baseHtml, sections) {
        var self = this;
        var map = {};
        var errors = [];
        (sections || []).forEach(function (s) {
            var p = self.parseSection(s && s.name, s && s.html);
            if (!p || !p.id) {
                errors.push('Could not identify a section id for "' + ((s && s.name) || 'an uploaded file') +
                    '" (no PAGEFORGE-SECTION marker and no __part-NN / -NN filename).');
                return;
            }
            if (map[p.id] !== undefined) {
                errors.push('Duplicate section id "' + p.id + '" (two uploaded files claim the same slot).');
                return;
            }
            map[p.id] = p.content;
        });
        return this.stitchCore(baseHtml, map, errors);
    }

    // ------------------------------------------------------------------
    // Pure core: stitch over an id → content map
    // ------------------------------------------------------------------

    /**
     * @param {string} baseHtml
     * @param {Object<string,string>} sectionMap - id → section content.
     * @param {string[]} [priorErrors]
     * @returns {{ok:boolean, html:?string, errors:string[], placements:Array}}
     */
    stitchCore(baseHtml, sectionMap, priorErrors) {
        var errors = (priorErrors || []).slice();
        sectionMap = sectionMap || {};

        // Strip manual-stitch GUIDE blocks from the base BEFORE locating markers, so
        // guidance that quotes a splice marker can't be mistaken for a real slot.
        baseHtml = this._stripGuides(baseHtml);

        var markers = this.findSpliceMarkers(baseHtml);
        if (!markers.length) {
            errors.push('No PAGEFORGE-SPLICE markers found in the base homepage — is this a SPLIT-MODE base?');
        }

        var seen = {};
        markers.forEach(function (m) {
            if (seen[m.id]) { errors.push('Duplicate splice slot "' + m.id + '" in the base homepage.'); }
            seen[m.id] = true;
        });
        var baseIds = markers.map(function (m) { return m.id; });

        // Every slot must have a section; every section must match a slot.
        markers.forEach(function (m) {
            if (sectionMap[m.id] === undefined) {
                errors.push('Missing section for slot "' + m.id + '" (no uploaded file fills it).');
            }
        });
        Object.keys(sectionMap).forEach(function (id) {
            if (baseIds.indexOf(id) === -1) {
                errors.push('Extra section "' + id + '" has no matching slot in the base homepage.');
            }
        });

        if (errors.length) {
            return { ok: false, html: null, errors: errors, placements: [] };
        }

        var spliceRe = this._spliceRe();
        var html = baseHtml.replace(spliceRe, function (full, id) {
            return sectionMap[id] !== undefined ? sectionMap[id] : full;
        });
        // Strip any GUIDE blocks carried in from the section content too, so the
        // unified output contains none of the manual-stitch instructions.
        html = this._stripGuides(html);
        var placements = markers.map(function (m) { return { id: m.id, filled: true }; });
        return { ok: true, html: html, errors: [], placements: placements };
    }

    // ------------------------------------------------------------------
    // Parsing helpers
    // ------------------------------------------------------------------

    /** Ordered list of splice markers in the base: [{id, raw, index}]. */
    findSpliceMarkers(baseHtml) {
        var re = this._spliceRe();
        var out = [], m;
        while ((m = re.exec(String(baseHtml || ''))) !== null) {
            out.push({ id: m[1], raw: m[0], index: m.index });
        }
        return out;
    }

    /**
     * Identify a section file's id + content. Precedence:
     *   1. explicit <!-- PAGEFORGE-SECTION id="X" --> … <!-- /PAGEFORGE-SECTION -->
     *   2. a full page → the inner HTML of its #body
     *   3. the whole file (a bare fragment) — id from the filename
     * @returns {{id:?string, content:string, source:string}}
     */
    parseSection(name, html) {
        html = String(html == null ? '' : html);
        var cfg = this.config;

        var startRe = new RegExp('<!--\\s*' + cfg.sectionTag + '\\s+id=["\']?([\\w.\\-]+)["\']?\\s*-->', 'i');
        var sm = startRe.exec(html);
        if (sm) {
            var rest = html.slice(sm.index + sm[0].length);
            var endRe = new RegExp('<!--\\s*/' + cfg.sectionTag + '\\s*-->', 'i');
            var em = endRe.exec(rest);
            var content = em ? rest.slice(0, em.index) : rest;
            return { id: String(sm[1]).toLowerCase(), content: this._trim(content), source: 'marker' };
        }

        var bodyInner = this._extractBodyInner(html);
        if (bodyInner !== null) {
            return { id: this._idFromName(name), content: this._trim(bodyInner), source: 'body' };
        }
        return { id: this._idFromName(name), content: this._trim(html), source: 'whole' };
    }

    /** Section id from a filename: -lesson-NN / -section-NN / __part-NN / trailing -NN. */
    _idFromName(name) {
        var base = String(name || '').replace(/^.*[\\/]/, '').replace(/\.html?$/i, '');
        var m = /(?:__part-|__section-|-lesson-|-section-)([\w.]+)$/i.exec(base) || /-(\d{1,3})$/.exec(base);
        return m ? String(m[1]).toLowerCase() : null;
    }

    /** Inner HTML of the first <div id="body"> … </div> (balanced), or null. */
    _extractBodyInner(html) {
        var m = /<div\b[^>]*\bid="body"[^>]*>/i.exec(html);
        if (!m) { return null; }
        var start = m.index + m[0].length;
        var tagRe = /<div\b|<\/div>/ig;
        tagRe.lastIndex = m.index;
        var depth = 0, mm, end = -1;
        while ((mm = tagRe.exec(html)) !== null) {
            if (mm[0] === '</div>') { depth--; if (depth === 0) { end = mm.index; break; } }
            else { depth++; }
        }
        return end > start ? html.slice(start, end) : html.slice(start);
    }

    _trim(s) {
        return String(s).replace(/^[ \t]*\r?\n/, '').replace(/\s+$/, '');
    }

    _spliceRe() {
        return new RegExp('<!--\\s*' + this.config.spliceTag + '\\s+id=["\']?([\\w.\\-]+)["\']?\\s*-->', 'ig');
    }

    /**
     * Remove the manual-stitch GUIDE blocks the Convertor adds for developers who
     * hand-assemble the split files: everything from <!-- PAGEFORGE-GUIDE-START -->
     * to <!-- PAGEFORGE-GUIDE-END --> (inclusive, plus a trailing blank line), so
     * the automated stitch carries none of the manual instructions. Anchored on the
     * unique END sentinel (non-greedy) → safe even when the guidance text quotes
     * markers that themselves contain "-->".
     */
    _stripGuides(html) {
        var cfg = this.config;
        if (!cfg.guideStartTag || !cfg.guideEndTag) { return String(html == null ? '' : html); }
        var re = new RegExp(
            '[ \\t]*<!--\\s*' + cfg.guideStartTag + '\\s*-->[\\s\\S]*?<!--\\s*' + cfg.guideEndTag + '\\s*-->[ \\t]*(?:\\r?\\n)?',
            'ig');
        return String(html == null ? '' : html).replace(re, '');
    }

    // ------------------------------------------------------------------
    // Convenience for the adapter
    // ------------------------------------------------------------------

    /** Derive the module code from a base homepage (#module-code, <title>, filename). */
    moduleCode(baseHtml, baseName) {
        var mc = /<div\b[^>]*\bid="module-code"[^>]*>\s*<h1[^>]*>([^<]+)<\/h1>/i.exec(String(baseHtml || ''));
        if (mc && mc[1].trim()) { return mc[1].trim(); }
        var t = /<title[^>]*>([^<]+)<\/title>/i.exec(String(baseHtml || ''));
        if (t && t[1].trim()) { return t[1].trim().split(/\s+/)[0]; }
        var fn = /([A-Za-z]{2,}\d{2,}[A-Za-z]?)/.exec(String(baseName || ''));
        return fn ? fn[1].toUpperCase() : 'MODULE';
    }

    /** A short human-readable placement summary for the toast / on-screen note. */
    summary(result) {
        if (!result) { return ''; }
        if (!result.ok) { return 'Stitch failed: ' + result.errors.join(' '); }
        return 'Stitched ' + result.placements.length + ' section' +
            (result.placements.length === 1 ? '' : 's') + ' into one unified page.';
    }

    // ------------------------------------------------------------------
    // INTERACTIVE INSERTION (pure core) — contract §10
    // ------------------------------------------------------------------

    /**
     * Normalise any form of the hand-off reference to the bare page id.
     * The page marker's data-cv2-ref is already bare ("XDLS908-01-01"); the
     * .txt / built file carries the full code ("XDLS908-INT-01-01-dragAndDrop").
     * Both normalise to the SAME uppercase key so either form matches.
     */
    bareRefId(ref) {
        if (ref == null) { return null; }
        var s = String(ref).trim();
        if (!s) { return null; }
        var m = /^([A-Za-z][A-Za-z0-9]*)-INT-(\d{2,})-(\d{2,})(?:-|$)/i.exec(s);
        if (m) { return (m[1] + '-' + m[2] + '-' + m[3]).toUpperCase(); }
        return s.toUpperCase();
    }

    /** All cv2-int-ref reference markers in a generated page (extract mode). */
    findIntRefMarkers(html) {
        var cfg = PageStitcher.INTERACTIVES, self = this;
        html = String(html == null ? '' : html);
        return this._scanClassElements(html, cfg.markerClass).map(function (e) {
            var inner = html.slice(e.innerStart, e.innerEnd);
            var label = inner.replace(/<[^>]*>/g, ' ').replace(/\s+/g, ' ').trim();
            return {
                bareId: self._attrFromTag(e.open, cfg.refAttr),
                label: label || null,
                start: e.start,
                end: e.end
            };
        });
    }

    /** All <section class="cv2-built" data-cv2-ref="…"> builds in an uploaded file. */
    parseBuiltSections(html) {
        var cfg = PageStitcher.INTERACTIVES, self = this;
        html = String(html == null ? '' : html);
        return this._scanClassElements(html, cfg.builtClass).map(function (e) {
            return {
                ref: self._attrFromTag(e.open, cfg.refAttr),
                content: self._trim(html.slice(e.innerStart, e.innerEnd)),
                unclosed: !!e.unclosed
            };
        });
    }

    /**
     * Replace every matched marker in one page with its build (back to front so
     * indices stay valid). Unmatched markers are LEFT IN PLACE — the loud marker
     * stays visible and the page remains a valid input for a later pass with the
     * missing built file(s).
     * @param {string} pageHtml
     * @param {Object<string,{ref:string,content:string,file:string,used:boolean}>} index bare-id → build
     */
    insertInteractives(pageHtml, index) {
        var html = String(pageHtml == null ? '' : pageHtml);
        var markers = this.findIntRefMarkers(html);
        var placed = [], missing = [];
        for (var i = markers.length - 1; i >= 0; i--) {
            var mk = markers[i];
            var key = this.bareRefId(mk.bareId || mk.label);
            var hit = key ? index[key] : null;
            if (hit) {
                html = html.slice(0, mk.start) + hit.content + html.slice(mk.end);
                hit.used = true;
                placed.unshift({ ref: hit.ref, bareId: key });
            } else {
                missing.unshift({ bareId: mk.bareId, label: mk.label });
            }
        }
        return { html: html, markerCount: markers.length, placed: placed, missing: missing };
    }

    /**
     * The interactive-insertion orchestrator (pure).
     * @param {Array<{name:string,html:string}>} pageFiles - generated module pages.
     * @param {Array<{name:string,html:string}>} builtFiles - built-interactives file(s).
     * @returns {{ok:boolean, pages:Array, errors:string[], warnings:string[],
     *            stats:?{markers:number,placed:number,missing:number,builds:number},
     *            moduleCode:?string}}
     */
    stitchInteractives(pageFiles, builtFiles) {
        var self = this;
        var errors = [], warnings = [];
        var index = {};

        (builtFiles || []).forEach(function (f) {
            if (!f) { return; }
            var secs = self.parseBuiltSections(f.html);
            if (!secs.length) {
                errors.push('"' + (f.name || 'an uploaded file') + '" looks like a built-interactives file but holds no ' +
                    '<section class="cv2-built" data-cv2-ref="…"> block.');
                return;
            }
            secs.forEach(function (s) {
                if (!s.ref) {
                    errors.push('A build in "' + f.name + '" is missing its data-cv2-ref reference code — every built ' +
                        'interactive must keep the exact REFERENCE CODE from the .txt worklist.');
                    return;
                }
                if (s.unclosed) {
                    errors.push('The build "' + s.ref + '" in "' + f.name + '" is never closed (missing </section>).');
                    return;
                }
                var key = self.bareRefId(s.ref);
                if (index[key]) {
                    errors.push('Reference code "' + s.ref + '" appears twice (in "' + index[key].file + '" and "' +
                        f.name + '") — each code must be built exactly once.');
                    return;
                }
                if (!s.content) {
                    errors.push('The build "' + s.ref + '" in "' + f.name + '" is empty.');
                    return;
                }
                index[key] = { ref: s.ref, content: s.content, file: f.name, used: false };
            });
        });

        if (!(pageFiles && pageFiles.length)) {
            errors.push('No module page files found — upload the HTML pages from the HTML Generator together with the built-interactives file(s).');
        }
        if (!Object.keys(index).length && !errors.length) {
            errors.push('No built-interactives file found — include the file(s) downloaded from the Interactives Claude ' +
                'project (each build wrapped in <section class="cv2-built" data-cv2-ref="…">).');
        }

        var moduleCode = null;
        var ks = Object.keys(index);
        if (ks.length) { moduleCode = ks[0].replace(/-\d{2,}-\d{2,}$/, ''); }

        var pages = [], totalMarkers = 0, placedCount = 0, missingCount = 0;
        (pageFiles || []).forEach(function (f) {
            if (!f) { return; }
            var r = self.insertInteractives(f.html, index);
            totalMarkers += r.markerCount;
            placedCount += r.placed.length;
            r.missing.forEach(function (mm) {
                missingCount++;
                warnings.push('No build uploaded for "' + (mm.label || mm.bareId || 'unknown code') +
                    '" — its reference marker was left in place in ' + f.name +
                    ' (stitch that page again later with the missing built file).');
            });
            var includesAdded = [];
            if (r.placed.length) {
                var inj = self._injectHeadIncludes(r.html);
                r.html = inj.html;
                includesAdded = inj.added;
            }
            pages.push({
                name: f.name, html: r.html, placed: r.placed, missing: r.missing,
                includesAdded: includesAdded, changed: r.placed.length > 0
            });
        });

        if (!totalMarkers && pageFiles && pageFiles.length && !errors.length) {
            errors.push('None of the uploaded pages contains a reference marker (class "cv2-int-ref") — generate the module ' +
                'with the HTML Generator (its default hand-off puts a reference-code box at every un-built ' +
                'interactive), then upload those pages.');
        }

        Object.keys(index).forEach(function (k) {
            if (!index[k].used) {
                warnings.push('The build "' + index[k].ref + '" (' + index[k].file + ') matched no reference marker in the ' +
                    'uploaded pages — check the pages come from the same conversion.');
            }
        });

        if (errors.length) {
            return { ok: false, pages: [], errors: errors, warnings: warnings, stats: null, moduleCode: moduleCode };
        }
        return {
            ok: true, pages: pages, errors: [], warnings: warnings, moduleCode: moduleCode,
            stats: { markers: totalMarkers, placed: placedCount, missing: missingCount, builds: ks.length }
        };
    }

    // ------------------------------------------------------------------
    // Generic element scanning (shared by the interactive core)
    // ------------------------------------------------------------------

    /**
     * Inject required page-head script includes for placed builds whose widget
     * class demands one (crossword / wordFind — the template library's only two
     * script-dependency widgets). No-ops when the include is already present,
     * the class is absent, or the page has no </head>.
     * @returns {{html:string, added:string[]}}
     */
    _injectHeadIncludes(html) {
        html = String(html == null ? '' : html);
        var list = (PageStitcher.INTERACTIVES && PageStitcher.INTERACTIVES.headIncludes) || [];
        var added = [];
        for (var i = 0; i < list.length; i++) {
            var d = list[i];
            var clsRe = new RegExp('class="[^"]*\\b' + d.token + '\\b[^"]*"');
            if (!clsRe.test(html)) { continue; }
            if (html.indexOf(d.needle) !== -1) { continue; }
            var m = /<\/head>/i.exec(html);
            if (!m) { continue; }
            html = html.slice(0, m.index) + '    ' + d.include + '\n' + html.slice(m.index);
            added.push(d.needle);
        }
        return { html: html, added: added };
    }

    /** Read one attribute's value out of an element's open tag ("…" or '…'). */
    _attrFromTag(openTag, name) {
        var re = new RegExp(name + '\\s*=\\s*(?:"([^"]*)"|\'([^\']*)\')', 'i');
        var m = re.exec(String(openTag || ''));
        if (!m) { return null; }
        return m[1] !== undefined ? m[1] : m[2];
    }

    /**
     * Every element whose class attribute carries the given token, with balanced
     * start/end offsets. Nested elements inside a match are skipped (the scan
     * resumes after the matched element).
     */
    _scanClassElements(html, classToken) {
        html = String(html == null ? '' : html);
        var out = [];
        var openRe = /<([a-zA-Z][a-zA-Z0-9-]*)((?:[^>"']|"[^"]*"|'[^']*')*)>/g;
        var m;
        while ((m = openRe.exec(html)) !== null) {
            var open = m[0];
            if (open.slice(-2) === '/>') { continue; } // self-closing → can't carry content
            var cls = this._attrFromTag(open, 'class');
            if (!cls || (' ' + cls + ' ').indexOf(' ' + classToken + ' ') === -1) { continue; }
            var innerStart = m.index + open.length;
            var end = this._elementEnd(html, m[1], m.index);
            if (!end) {
                out.push({ tag: m[1], open: open, start: m.index, innerStart: innerStart, innerEnd: html.length, end: html.length, unclosed: true });
                break;
            }
            out.push({ tag: m[1], open: open, start: m.index, innerStart: innerStart, innerEnd: end.innerEnd, end: end.outerEnd });
            openRe.lastIndex = end.outerEnd;
        }
        return out;
    }

    /** Balanced end of the element whose open tag starts at fromIdx: {innerEnd, outerEnd}. */
    _elementEnd(html, tagName, fromIdx) {
        var re = new RegExp('<' + tagName + '\\b[^>]*>|</' + tagName + '\\s*>', 'ig');
        re.lastIndex = fromIdx;
        var depth = 0, m;
        while ((m = re.exec(html)) !== null) {
            if (m[0].charAt(1) === '/') {
                depth--;
                if (depth === 0) { return { innerEnd: m.index, outerEnd: m.index + m[0].length }; }
            } else if (m[0].slice(-2) === '/>') {
                if (depth === 0) { return { innerEnd: re.lastIndex, outerEnd: re.lastIndex }; }
            } else {
                depth++;
            }
        }
        return null;
    }
}

PageStitcher.DEFAULTS = {
    spliceTag: 'PAGEFORGE-SPLICE',
    sectionTag: 'PAGEFORGE-SECTION',
    guideStartTag: 'PAGEFORGE-GUIDE-START',
    guideEndTag: 'PAGEFORGE-GUIDE-END'
};

/**
 * The interactive-insertion contract (matches the V2 converter's extract mode —
 * Emit_Templates.json interactive_placeholder.extract — and the Interactives
 * Claude project's output contract):
 *   page marker:  <div class="cv2-int-ref" data-cv2-index="…" data-cv2-ref="CODE-NN-SS">CODE-INT-NN-SS-type</div>
 *   built block:  <section class="cv2-built" data-cv2-ref="CODE-INT-NN-SS-type"> …finished widget HTML… </section>
 */
PageStitcher.INTERACTIVES = {
    markerClass: 'cv2-int-ref',
    builtClass: 'cv2-built',
    refAttr: 'data-cv2-ref',
    // The only two data-driven widgets that REQUIRE a page-head script include
    // (per All_Interactives — the template source of truth). A placed build
    // carrying one of these wrapper classes gets its include injected into the
    // page <head> if not already present, mirroring how the human-built module
    // library ships them.
    headIncludes: [
        { token: 'crossword', needle: 'crossword.js', include: '<script type="text/javascript" src="js/crossword.js"></script>' },
        { token: 'wordFind', needle: 'wordFind.js', include: '<script type="text/javascript" src="js/wordFind.js"></script>' }
    ]
};


/**
 * PageStitcherMode — the thin DOM/upload adapter for the Page Stitcher front
 * page (#stitch-section): one accumulating upload container, a Stitch action, the
 * finished download (via OutputManager) and a placement summary. State + the
 * stitch orchestration are pure (dependencies injected) so the Node runner
 * exercises them; every DOM touch no-ops when an element is absent. Mirrors the
 * carried-over ModeToggle adapter conventions.
 *
 * UPLOAD BEHAVIOUR (2026-07-30):
 *   • ADDITIVE — every drop / browse ADDS to the staged set, because the two
 *     halves of an interactive-insertion job arrive in separate folders (the
 *     generated pages in one, the built interactives in another) and therefore
 *     take separate drag-and-drop actions. Same filename twice = replaced in place.
 *   • VISIBLE + EDITABLE — every staged file is listed with a ✕ that removes just
 *     that file, so the set can be corrected before Stitch is pressed.
 *   • The `{CODE}_interactives.txt` worklist is silently discarded on arrival
 *     (see isIgnoredUpload) — it ships in the same zip as the pages and has no
 *     part to play once the interactives are built.
 */
class PageStitcherMode {
    constructor(options) {
        options = options || {};
        this._document = options.document || null;
        this._stitcher = options.stitcher || null;
        this._outputManager = options.outputManager || null;
        this._notify = options.notify || null;

        /** @type {Array} all staged files — base + sections together (one container) */
        this.files = [];
        this.els = {};

        if (this._document && options.autoInit !== false) { this.init(); }
    }

    // ------------------------------------------------------------------
    // State (pure)
    // ------------------------------------------------------------------

    /**
     * ACCUMULATING upload (2026-07-30). The two halves of an interactive-insertion
     * job normally live in DIFFERENT folders (the HTML Generator's zip extracts to
     * one, the Interactives Claude project's zip to another), so the container must
     * survive several drag-and-drop actions: each drop ADDS to what is already
     * staged instead of replacing it. Re-adding the same FILENAME replaces that one
     * entry in place (newest wins) so a corrected file can simply be dropped again.
     * @param {FileList|Array} files
     * @returns {number} the staged-file count after the add
     */
    addFiles(files) {
        var incoming = this._normaliseIncoming(files);
        var self = this;
        incoming.forEach(function (f) {
            var at = self._indexOfName(f && f.name);
            if (at === -1) { self.files.push(f); } else { self.files[at] = f; }
        });
        this._renderFiles();
        this._syncStitch();
        return this.files.length;
    }

    /** Replace every staged file (used by a reset / a programmatic set). */
    setFiles(files) {
        this.files = this._normaliseIncoming(files);
        this._renderFiles();
        this._syncStitch();
        return this.files.length;
    }

    /** Drop one staged file by position (the ✕ beside its name). */
    removeFile(index) {
        if (index >= 0 && index < this.files.length) { this.files.splice(index, 1); }
        this._renderFiles();
        this._syncStitch();
        return this.files.length;
    }

    /** Drop every staged file. */
    clearFiles() { return this.setFiles([]); }

    hasFiles() { return Array.isArray(this.files) && this.files.length > 0; }
    /** Stitch is enabled with at least two files (a base homepage + ≥1 section). */
    canStitch() { return this.files.length >= 2; }

    /** Staged position of a filename (case-insensitive), or -1. */
    _indexOfName(name) {
        var key = String(name == null ? '' : name).toLowerCase();
        for (var i = 0; i < this.files.length; i++) {
            var n = this.files[i] && this.files[i].name;
            if (String(n == null ? '' : n).toLowerCase() === key) { return i; }
        }
        return -1;
    }

    /**
     * Files the Page Stitcher never uses and takes in silently. The HTML
     * Generator emits its pages and a `{CODE}_interactives.txt` worklist into one
     * zip, so "select all" easily sweeps the worklist in alongside the pages — by
     * stitch time the built interactives already exist, so the worklist has no
     * part to play. It is simply not staged: no warning, no summary line.
     */
    static isIgnoredUpload(name) {
        return /_interactives\.txt$/i.test(String(name == null ? '' : name));
    }

    /** A FileList / array → a plain array, minus anything the stitcher never uses. */
    _normaliseIncoming(files) {
        var out = [];
        if (files && files.length) {
            for (var i = 0; i < files.length; i++) {
                var f = files[i];
                if (!f || PageStitcherMode.isIgnoredUpload(f.name)) { continue; }
                out.push(f);
            }
        }
        return out;
    }

    // ------------------------------------------------------------------
    // Stitch orchestration (core — operates on already-read {name,html})
    // ------------------------------------------------------------------

    /**
     * Classify the read files into the base homepage vs section files, then
     * stitch. The base is the file carrying PAGEFORGE-SPLICE markers (or named
     * <CODE>-base.html); everything else is a section.
     * @param {Array<{name:string,html:string}>} readFiles
     * @returns {{result:Object, filename:?string}}
     */
    stitchReadFiles(readFiles) {
        var stitcher = this._getStitcher();
        if (!stitcher) {
            return this._fail(['Stitcher unavailable.'], 'Stitch failed — stitcher unavailable.');
        }
        // AUTO-DETECT which job this upload is (contract §10): any file carrying
        // cv2-built builds or cv2-int-ref markers → interactive insertion;
        // otherwise the original split-mode lesson stitch. .txt worklists are
        // set aside either way.
        var part = this._partitionUploads(readFiles, stitcher);
        if (part.kind === 'interactives') {
            return this._stitchInteractiveUploads(part, stitcher);
        }
        var c = this._classifyFiles(part.pages, stitcher);
        if (!c.base) {
            return this._fail(
                ['No base homepage found — include the base file (it carries PAGEFORGE-SPLICE markers, or is named <CODE>-base.html).'],
                'Stitch failed — no base homepage in the upload.');
        }
        if (c.extraBases.length) {
            return this._fail(['More than one base homepage uploaded — include exactly one.'],
                'Stitch failed — more than one base homepage.');
        }

        var result = stitcher.stitch(c.base.html, c.sections);
        var filename = null;
        if (result.ok) {
            filename = stitcher.moduleCode(c.base.html, c.base.name) + '.html';
            var om = this._getOutputManager();
            if (om) {
                om.addFile({ filename: filename, content: result.html, type: 'html' });
                try { om.downloadFile(filename); } catch (e) { /* headless / no DOM */ }
            }
        } else {
            this._toast('Stitch failed — see the summary.');
        }
        this._renderSummary(result, filename);
        return { result: result, filename: filename };
    }

    /** Split the read files into {base, extraBases, sections} by marker/filename. */
    _classifyFiles(readFiles, stitcher) {
        var tag = (stitcher && stitcher.config && stitcher.config.spliceTag) || 'PAGEFORGE-SPLICE';
        // Match a REAL splice marker (<!-- PAGEFORGE-SPLICE id=…), not a bare mention
        // of the word: every section file carries a manual-stitch GUIDE block that
        // quotes the marker in its human instructions, so a bare-substring test
        // misclassifies every section as a base (→ ">1 base" error). Strip GUIDE
        // blocks first — exactly as stitchCore does before locating markers — then
        // look for a genuine marker. The <CODE>-base.html filename fallback is kept.
        var markerRe = new RegExp('<!--\\s*' + tag + '\\s+id=', 'i');
        var bases = [], sections = [];
        (readFiles || []).forEach(function (f) {
            if (!f) { return; }
            var cleaned = (stitcher && typeof stitcher._stripGuides === 'function')
                ? stitcher._stripGuides(f.html || '') : (f.html || '');
            var isBase = markerRe.test(cleaned) ||
                /(^|[\\/])[^\\/]*-base\.html?$/i.test(f.name || '');
            if (isBase) { bases.push(f); } else { sections.push(f); }
        });
        return { base: bases[0] || null, extraBases: bases.slice(1), sections: sections };
    }

    /**
     * Partition an upload for mode detection: .txt worklists set aside; a file
     * carrying <section class="cv2-built" data-cv2-ref> builds is a
     * built-interactives file; a page carrying cv2-int-ref markers flags the
     * upload as interactive insertion. Anything else stays a candidate page /
     * lesson file for whichever mode runs.
     */
    _partitionUploads(readFiles, stitcher) {
        var txt = [], built = [], pages = [], hasMarkers = false;
        (readFiles || []).forEach(function (f) {
            if (!f) { return; }
            // The generated worklist is dropped in silence wherever it arrives —
            // the upload filter is the first line, this is the second (a caller
            // may hand read files straight to stitchReadFiles).
            if (PageStitcherMode.isIgnoredUpload(f.name)) { return; }
            if (/\.txt$/i.test(f.name || '')) { txt.push(f); return; }
            var html = f.html || '';
            if (html.indexOf(PageStitcher.INTERACTIVES.builtClass) !== -1 &&
                stitcher.parseBuiltSections(html).length) { built.push(f); return; }
            if (html.indexOf(PageStitcher.INTERACTIVES.markerClass) !== -1) { hasMarkers = true; }
            pages.push(f);
        });
        return {
            kind: (built.length || hasMarkers) ? 'interactives' : 'split',
            txt: txt, built: built, pages: pages
        };
    }

    /** The interactive-insertion path: place the builds, download the finished pages. */
    _stitchInteractiveUploads(part, stitcher) {
        var res = stitcher.stitchInteractives(part.pages, part.built);
        var filename = null;
        if (res.ok) {
            var code = res.moduleCode ||
                stitcher.moduleCode(part.pages[0] && part.pages[0].html, part.pages[0] && part.pages[0].name) || 'MODULE';
            filename = res.pages.length === 1 ? res.pages[0].name : code + '-final.zip';
            var om = this._getOutputManager();
            if (om) {
                if (typeof om.clear === 'function') { om.clear(); }
                res.pages.forEach(function (p) {
                    om.addFile({ filename: p.name, content: p.html, type: 'html' });
                });
                if (res.pages.length === 1) {
                    try { om.downloadFile(filename); } catch (e) { /* headless / no DOM */ }
                } else {
                    try {
                        var pr = om.downloadAsZip(filename);
                        if (pr && typeof pr.catch === 'function') { pr.catch(function () { /* headless / no JSZip */ }); }
                    } catch (e) { /* headless / no DOM */ }
                }
            }
        } else {
            this._toast('Stitch failed — see the summary.');
        }
        this._renderInteractiveSummary(res, filename, part);
        return { result: res, filename: filename };
    }

    _fail(errors, toast) {
        var result = { ok: false, errors: errors, placements: [] };
        this._toast(toast);
        this._renderSummary(result, null);
        return { result: result, filename: null };
    }

    /** Read the staged files then stitch. Returns a Promise in the browser. */
    stitchNow() {
        var self = this;
        if (!this.canStitch()) {
            this._toast('Add the base homepage and its section files (at least two files) first.');
            return null;
        }
        var reads = this.files.map(function (f) { return self._read(f); });
        return this._resolveAll(reads, function (arr) {
            return self.stitchReadFiles(arr.filter(Boolean));
        });
    }

    _read(file) {
        if (!file) { return null; }
        if (typeof file.html === 'string') { return { name: file.name || 'file.html', html: file.html }; }
        if (typeof file.text === 'function') {
            return file.text().then(function (t) { return { name: file.name || 'file.html', html: t }; });
        }
        return null;
    }
    _resolveAll(arr, fn) {
        var any = arr.some(function (v) { return v && typeof v.then === 'function'; });
        if (!any) { return fn(arr); }
        return Promise.all(arr.map(function (v) { return Promise.resolve(v); })).then(fn);
    }
    _getStitcher() {
        if (!this._stitcher && typeof PageStitcher !== 'undefined') { this._stitcher = new PageStitcher(); }
        return this._stitcher;
    }
    _getOutputManager() {
        if (!this._outputManager && typeof OutputManager !== 'undefined') { this._outputManager = new OutputManager(); }
        return this._outputManager;
    }
    _toast(msg) {
        if (typeof this._notify === 'function') { this._notify(msg); return; }
        if (typeof window !== 'undefined' && window.pageForgeToast && window.pageForgeToast.show) {
            window.pageForgeToast.show(msg);
        }
    }

    // ------------------------------------------------------------------
    // DOM adapter (no-ops when unbound / an element is absent)
    // ------------------------------------------------------------------

    init() {
        if (!this._document) { return; }
        var doc = this._document, self = this;
        function get(id) { return doc.getElementById ? doc.getElementById(id) : null; }
        this.els = {
            input: get('stitch-input'), drop: get('stitch-drop'),
            info: get('stitch-info'), name: get('stitch-name'),
            list: get('stitch-file-list'), clearBtn: get('btn-stitch-clear'),
            stitchBtn: get('btn-stitch'), summary: get('stitch-summary')
        };
        // Every drop / browse ADDS to the staged set (see addFiles).
        this._bindFile(this.els.input, this.els.drop, function (files) { self.addFiles(files); });
        if (this.els.clearBtn && this.els.clearBtn.addEventListener) {
            this.els.clearBtn.addEventListener('click', function () { self.clearFiles(); });
        }
        if (this.els.stitchBtn && this.els.stitchBtn.addEventListener) {
            this.els.stitchBtn.addEventListener('click', function () { self.stitchNow(); });
        }
        this._renderFiles();
        this._syncStitch();
    }
    _bindFile(input, drop, onFiles) {
        if (input && input.addEventListener) {
            input.addEventListener('change', function () {
                onFiles(input.files);
                // Clear the control so picking the SAME file again still fires
                // change — otherwise a re-add after a ✕ removal would do nothing.
                try { input.value = ''; } catch (e) { /* older browsers */ }
            });
        }
        if (drop && drop.addEventListener) {
            drop.addEventListener('click', function () { if (input && input.click) { input.click(); } });
            drop.addEventListener('keydown', function (e) {
                if (e && (e.key === 'Enter' || e.key === ' ')) { if (e.preventDefault) { e.preventDefault(); } if (input && input.click) { input.click(); } }
            });
            drop.addEventListener('dragover', function (e) { if (e && e.preventDefault) { e.preventDefault(); } if (drop.classList) { drop.classList.add('drag-over'); } });
            drop.addEventListener('dragleave', function () { if (drop.classList) { drop.classList.remove('drag-over'); } });
            drop.addEventListener('drop', function (e) {
                if (e && e.preventDefault) { e.preventDefault(); }
                if (drop.classList) { drop.classList.remove('drag-over'); }
                var files = e && e.dataTransfer && e.dataTransfer.files;
                if (files && files.length) { onFiles(files); }
            });
        }
    }
    /**
     * The staged-file panel: a running count plus one row per file with a ✕ that
     * removes just that file, so the set can be corrected BEFORE Stitch is pressed.
     */
    _renderFiles() {
        var self = this, doc = this._document;
        if (this.els.name) {
            this.els.name.textContent = this.hasFiles()
                ? (this.files.length + ' file' + (this.files.length === 1 ? '' : 's') +
                   ' ready to stitch — drop more to add them')
                : '';
        }
        this._setHidden(this.els.info, !this.hasFiles());
        this._setHidden(this.els.clearBtn, !this.hasFiles());

        var list = this.els.list;
        if (!list) { return; }
        this._setHidden(list, !this.hasFiles());
        if (typeof list.removeChild === 'function') {
            while (list.lastChild) { list.removeChild(list.lastChild); }
        }
        if (list.innerHTML !== undefined) { list.innerHTML = ''; }
        if (!doc || !doc.createElement) { return; }
        this.files.forEach(function (f, i) {
            var label = (f && f.name) ? String(f.name) : 'file';
            var li = doc.createElement('li');
            li.className = 'staged-file-row';
            var nm = doc.createElement('span');
            nm.className = 'staged-file-row-name';
            nm.textContent = label;
            var btn = doc.createElement('button');
            btn.type = 'button';
            btn.className = 'staged-file-remove';
            btn.setAttribute('aria-label', 'Remove ' + label);
            btn.title = 'Remove ' + label;
            btn.textContent = '×';
            btn.addEventListener('click', function () { self.removeFile(i); });
            li.appendChild(nm);
            li.appendChild(btn);
            list.appendChild(li);
        });
    }
    _syncStitch() { if (this.els.stitchBtn) { this.els.stitchBtn.disabled = !this.canStitch(); } }
    _renderSummary(result, filename) {
        var el = this.els.summary;
        if (!el) { return; }
        var esc = function (s) { return String(s == null ? '' : s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;'); };
        if (result && result.ok) {
            el.innerHTML = '<p class="stitch-ok">✓ Stitched ' + result.placements.length + ' section' +
                (result.placements.length === 1 ? '' : 's') + ' into <code>' + esc(filename) + '</code> (downloaded).</p>';
        } else {
            var items = (result && result.errors || []).map(function (e) { return '<li>' + esc(e) + '</li>'; }).join('');
            el.innerHTML = '<p class="stitch-error">Could not stitch — nothing was downloaded:</p><ul class="stitch-errors">' + items + '</ul>';
        }
        this._setHidden(el, false);
    }
    /** Summary rendering for the interactive-insertion mode (page-by-page counts + warnings). */
    _renderInteractiveSummary(res, filename, part) {
        var el = this.els.summary;
        if (!el) { return; }
        var esc = function (s) { return String(s == null ? '' : s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;'); };
        var out = '';
        if (res && res.ok) {
            var s = res.stats || {};
            out += '<p class="stitch-ok">✓ Interactives placed: ' + s.placed + ' of ' + s.markers +
                ' reference marker' + (s.markers === 1 ? '' : 's') + ' across ' + res.pages.length +
                ' page' + (res.pages.length === 1 ? '' : 's') + ' — downloaded as <code>' + esc(filename) + '</code>.</p>';
            var lines = res.pages.filter(function (p) { return p.changed || p.missing.length; }).map(function (p) {
                return '<li><code>' + esc(p.name) + '</code> — ' + p.placed.length + ' placed' +
                    (p.missing.length ? ', ' + p.missing.length + ' still to place' : '') +
                    (p.includesAdded && p.includesAdded.length ? ' (+ added ' + esc(p.includesAdded.join(', ')) + ' include)' : '') + '</li>';
            }).join('');
            if (lines) { out += '<ul class="stitch-errors">' + lines + '</ul>'; }
        } else {
            out += '<p class="stitch-error">Could not stitch — nothing was downloaded:</p><ul class="stitch-errors">' +
                (res && res.errors || []).map(function (e) { return '<li>' + esc(e) + '</li>'; }).join('') + '</ul>';
        }
        if (res && res.warnings && res.warnings.length) {
            out += '<p class="stitch-error">Warning' + (res.warnings.length === 1 ? '' : 's') + ':</p><ul class="stitch-errors">' +
                res.warnings.map(function (w) { return '<li>' + esc(w) + '</li>'; }).join('') + '</ul>';
        }
        el.innerHTML = out;
        this._setHidden(el, false);
    }

    _setHidden(el, hidden) {
        if (el && el.classList) { if (hidden) { el.classList.add('hidden'); } else { el.classList.remove('hidden'); } }
    }
}

